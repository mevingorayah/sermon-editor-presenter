// Regenerates src/lib/sermon/export/appFontMetrics.ts from assets/fonts/export.
// Static instances made from the bundled variable fonts (opsz 24, wght 400/700).
import fs from "node:fs";
import * as fontkit from "fontkit";
const dir = "assets/fonts/export";
let chars = "";
for (let c = 0x20; c <= 0x17f; c++) if (c < 0x7f || c >= 0xa0) chars += String.fromCodePoint(c);
chars += "’‘“”‚„–—…•†‡‰‹›€™ƒˆ˜";
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".ttf")).sort()) {
  const font = fontkit.openSync(`${dir}/${f}`);
  const scale = 1000 / font.unitsPerEm;
  out[f.replace(/\.ttf$/, "")] = [...chars].map((ch) => {
    const g = font.glyphForCodePoint(ch.codePointAt(0));
    return g && g.id ? Math.round(g.advanceWidth * scale) : -1;
  });
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(",")}],`).join("\n");
fs.writeFileSync("src/lib/sermon/export/appFontMetrics.ts",
`/**
 * Advance widths (1/1000 em) of the export fonts in assets/fonts/export
 * (the 10 approved fonts + JetBrains Mono; see scripts/make-export-fonts.py). Pure data, safe in the browser.
 * Generated by scripts/gen-export-font-metrics.mjs; -1 = glyph missing.
 */
export const APP_METRIC_CHARS = ${JSON.stringify(chars)};

export const APP_WIDTHS: Record<string, readonly number[]> = {
${body}
};
`);

// Glyph coverage (cmap ranges) per export font + the symbol fallback's widths,
// so layout can measure (and renderers draw) missing glyphs in the fallback.
const cov = {};
const fbw = {};
const b36 = (n) => n.toString(36);
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".ttf")).sort()) {
  const font = fontkit.openSync(`${dir}/${f}`);
  const name = f.replace(/\.ttf$/, "");
  const cps = [...new Set(font.characterSet)].filter((c) => c <= 0xffff && font.glyphForCodePoint(c).id).sort((a, b) => a - b);
  const ranges = [];
  for (const c of cps) {
    const r = ranges[ranges.length - 1];
    if (r && r[1] === c - 1) r[1] = c; else ranges.push([c, c]);
  }
  cov[name] = ranges.map(([a, b]) => (a === b ? b36(a) : `${b36(a)}-${b36(b)}`)).join(",");
  if (name.startsWith("symbols-fallback-")) {
    const scale = 1000 / font.unitsPerEm;
    fbw[name] = cps.filter((c) => c >= 0x80).map((c) => `${b36(c)}:${b36(Math.round(font.glyphForCodePoint(c).advanceWidth * scale))}`).join(",");
  }
}
fs.writeFileSync("src/lib/sermon/export/appFontCoverage.ts",
`/**
 * Glyph coverage of the export fonts (base-36 code point ranges, BMP) and the
 * symbol fallback's advance widths (1/1000 em, "cp:w" base 36). Pure data.
 * Generated by scripts/gen-export-font-metrics.mjs.
 */
export const APP_COVERAGE: Record<string, string> = {
${Object.entries(cov).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
};

export const FALLBACK_WIDTHS: Record<string, string> = {
${Object.entries(fbw).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
};
`);
