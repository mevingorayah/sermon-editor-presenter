// Regenerates src/lib/sermon/export/appFontMetrics.ts from assets/fonts/export.
// Static instances made from the bundled variable fonts (opsz 24, wght 400/700).
import fs from "node:fs";
import * as fontkit from "fontkit";
const dir = "assets/fonts/export";
let chars = "";
for (let c = 0x20; c <= 0x17f; c++) if (c < 0x7f || c >= 0xa0) chars += String.fromCodePoint(c);
chars += "’‘“”‚„–—…•†‡‰‹›€™ƒˆ˜";
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".ttf")).sort()) {
  const font = fontkit.openSync(`${dir}/${f}`);
  const scale = 1000 / font.unitsPerEm;
  out[f.replace(/\.ttf$/, "")] = [...chars].map((ch) => {
    const g = font.glyphForCodePoint(ch.codePointAt(0));
    return g && g.id ? Math.round(g.advanceWidth * scale) : -1;
  });
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(",")}],`).join("\n");
fs.writeFileSync("src/lib/sermon/export/appFontMetrics.ts",
`/**
 * Advance widths (1/1000 em) of the export fonts in assets/fonts/export
 * (the 10 approved fonts + JetBrains Mono; see scripts/make-export-fonts.py). Pure data, safe in the browser.
 * Generated by scripts/gen-export-font-metrics.mjs; -1 = glyph missing.
 */
export const APP_METRIC_CHARS = ${JSON.stringify(chars)};

export const APP_WIDTHS: Record<string, readonly number[]> = {
${body}
};
`);
